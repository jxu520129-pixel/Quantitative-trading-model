def _keyword_hits(event_text: str) -> list[str]:
    return [
        industry
        for industry, info in INDUSTRY_CHAIN.items()
        if any(_hit_keyword(keyword, event_text) for keyword in info["keywords"])
    ]


def concept_industries(event_text: str) -> list[str]:
    """返回事件文本命中的「龙头公司 / 产品 / 技术术语」对应的标准行业。"""
    hits: list[str] = []
    for concept, chains in CONCEPT_TO_CHAIN.items():
        if concept in event_text:
            hits.extend(chains)
    return list(dict.fromkeys(hits))


def direct_industries(event_text: str) -> list[str]:
    """只返回事件文本**直接命中**的行业（行业关键词 + 概念词），不传导上下游。

    用于「事件 → 个股」的精确匹配。``affected_industries`` 会把上下游一并纳入，
    而 INDUSTRY_CHAIN 高度连通（半导体↔计算机↔通信↔化工↔电力设备 互为上下游），
    导致几乎所有科技类新闻的命中集合都包含「半导体」，不同事件于是匹配到同一批个股。
    精确匹配场景改走本函数。
    """
    return list(dict.fromkeys(_keyword_hits(event_text) + concept_industries(event_text)))


def affected_industries(event_text: str) -> list[str]:
    """返回事件文本命中的行业及其上下游（去重）。用于「个股事件分」这类聚合评分。"""
    base = direct_industries(event_text)
    hits = list(base)
    for industry in base:
        info = INDUSTRY_CHAIN.get(industry)
        if not info:
            continue
        hits.extend(info["upstream"])
        hits.extend(info["downstream"])
    return list(dict.fromkeys(hits))


def macro_industries(event_text: str) -> list[str]:
    """返回宏观政策 / 指标命中的受益行业（用于无行业词事件的兜底传导）。"""
    hits: list[str] = []
    for keyword, chains in MACRO_HINTS.items():
        if keyword in event_text:
            hits.extend(chains)
    return list(dict.fromkeys(hits))
